# -*- coding: utf-8 -*-
"""애널리스트 정확도·가중 컨센 결과 JSON → 마크다운 문서. 숫자는 전부 JSON 에서 넣는다.

    python3 _scripts/애널리스트_정확도_문서.py _manifest/데이터/애널리스트정확도_결과_2026-10-21.json 10_국내주식/_애널리스트_정확도_가중컨센_2026-10-21.md
"""
import json
import sys

R = json.load(open(sys.argv[1], encoding="utf-8"))
P = R["params"]
SEC_NAME = {"조선": "조선", "화장품": "화장품·미용의료", "인터넷게임": "인터넷·게임"}
L = []
w = L.append


def f0(x):
    return "—" if x is None else f"{x:,.0f}"


def pct(x, d=1):
    return "—" if x is None else f"{x * 100:.{d}f}%"


def sp(x):
    return "—" if x is None else f"{x * 100:+.1f}%p".replace("-", "−")


w(f"# 애널리스트 실적 추정 정확도 · 상위 {P['top']}명 가중 컨센 (기준 {P['asof']}, 원장)")
w("")
w("> **결론부터.** 프로그램은 돌아간다 — 업종별로 애널리스트의 분기 영업이익 추정을 DART 실적과 맞춰 정확도 순위를 매기고, "
  f"상위 {P['top']}명은 ×{P['w_top']:g}, 나머지는 ×{P['w_rest']:g} 로 가중 컨센을 낸다. "
  "**그러나 과거 분기로 돌려 본 결과(워크포워드), 상위 3명 가중은 단순 중앙값보다 정확하지 않았다.** "
  "정확도 순위가 다음 분기까지 이어지지 않기 때문이다(아래 §3). 그래서 이 문서는 **기본 컨센을 중앙값으로 두고**, "
  "상위 3명 가중값과 상위 3명의 개별 추정은 참고 열로 함께 보인다. 원장 이력이 쌓이면(분기마다 재실행) 이 판단을 다시 한다.")
w("")
w("| 항목 | 값 |")
w("|---|---|")
w(f"| 프로그램 | [`_scripts/애널리스트_정확도_가중컨센.py`](../_scripts/애널리스트_정확도_가중컨센.py) (맥미니, 원장 읽기 전용 사본) · 문서화 [`_scripts/애널리스트_정확도_문서.py`](../_scripts/애널리스트_정확도_문서.py) |")
w(f"| 결과 원자료 | [`애널리스트정확도_결과_{P['asof']}.json`](../_manifest/데이터/애널리스트정확도_결과_{P['asof']}.json) · 유니버스 [`애널리스트정확도_유니버스.json`](../_manifest/데이터/애널리스트정확도_유니버스.json) |")
w(f"| 채점 대상 | 분기 영업이익 추정(원장 `report_estimates`, 2021-07 이후) vs DART 분기 실적. 분기말 92일 전 – 30일 후 애널리스트별 마지막 추정 |")
w(f"| 정확도 지표 | 상대오차 = 내 APE − 같은 종목·분기 다른 추정자 APE 중앙값(추정자 3명 이상). 평균을 표본 수로 수축(×n/(n+{P['shrink']:g}))해 순위. 최소 {P['min_events']}건·{P['min_quarters']}개 분기 |")
w(f"| 가중 | 상위 {P['top']}명 ×{P['w_top']:g} · 나머지(순위 밖·미채점·증권사 미상) ×{P['w_rest']:g} — 실행 인자로 바꾼다 |")
w(f"| 현재 컨센 | {P['target']} 영업이익, 최근 {P['cur_days']}일(직전 분기 실적 발표 이후) 애널리스트별 최신 추정 · 네이버 컨센 {P['asof']} 스냅과 나란히 |")
w("")

w("## 1. 업종별 정확도 순위")
w("")
for sec, d in R["sectors"].items():
    w(f"### {SEC_NAME[sec]} — 유니버스 {d['universe']}종목 · 추정 {d['est_rows']:,}행 · 채점 이벤트(추정자 3명 이상) {d['scored_events']}건 · 순위권 {d['rated']}명")
    w("")
    w("| 순위 | 애널리스트 | 증권사(최근) | 상대오차(수축) | 상대오차 | APE 중앙값 | 채점 건수 | 분기 수 | 동료보다 정확했던 비율 |")
    w("|---:|---|---|---:|---:|---:|---:|---:|---:|")
    for i, r in enumerate(d["ranking"], 1):
        mark = " **★**" if r["analyst"] in d["top"] else ""
        w(f"| {i} | {r['analyst']}{mark} | {r['firm'] or '—'} | {sp(r['rel_shrunk'])} | {sp(r['rel'])} | {pct(r['ape_med'])} | {r['n']} | {r['quarters']} | {pct(r['beat'], 0)} |")
    w("")
w("> 상대오차가 **음수일수록** 같은 종목·분기를 추정한 동료보다 실적에 가까웠다는 뜻이다. ★ = 가중 대상 상위 3명. "
  "APE 중앙값은 종목 난이도에 따라 달라 사람끼리 직접 비교하지 않는다(상대오차가 그 보정이다).")
w("")

w("## 2. 백테스트 — 가중이 실제로 더 맞았나")
w("")
w("목표 분기 **이전** 이벤트만으로 순위를 매기고(그 분기 실적 60일 전까지), 그 분기에 상위 3명이 한 명 이상 들어 있는 종목들에서 컨센별 APE 를 비교했다.")
w("")
w("| 업종 | 비교 건수 | 단순 평균 | **중앙값** | 가중 중앙값 | 상위3 ×2 평균 | 상위3 ×3 평균 | 연속 가중 | 상위3만 | ×2 가 단순평균을 이긴 비율 |")
w("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
for sec, d in R["sectors"].items():
    b = d["backtest"]
    if not b:
        continue
    m = lambda k: pct(b[k]["mean"])
    best = min(("ape_eq", "ape_med", "ape_wmed", "ape_w", "ape_w3", "ape_cont", "ape_top"), key=lambda k: b[k]["mean"])
    cell = lambda k: f"**{m(k)}**" if k == best else m(k)
    w(f"| {SEC_NAME[sec]} | {b['n_groups']} | {cell('ape_eq')} | {cell('ape_med')} | {cell('ape_wmed')} | {cell('ape_w')} | {cell('ape_w3')} | {cell('ape_cont')} | {cell('ape_top')} | {pct(b['w_beats_eq'], 0)} |")
w("")
w("> 굵은 값이 그 업종에서 가장 정확한 방식(평균 APE 최소). **세 업종 모두 단순 중앙값이 가장 정확했다.** "
  "상위3 ×2 평균은 단순 평균보다는 조선에서만 나았다. 상위 3명 추정만 쓰면 오히려 나빠진다 — 표본이 3명으로 줄어 한 명의 큰 오차가 그대로 남는다.")
w("")

w("## 3. 왜 가중이 안 먹히나 — 정확도가 사람에게 붙어 있지 않다")
w("")
for sec, d in R["sectors"].items():
    p = d.get("persistence")
    if p:
        w(f"- **{SEC_NAME[sec]}**: 2025-06 이전·이후 둘 다 채점된 {p['n']}명의 순위상관 {p['spearman']:+.2f}, 전반기 상위 3명({', '.join(p['top3_first'])}) 중 후반기 상위 3명({', '.join(p['top3_second'])})에 남은 사람 {p['top3_overlap']}명.")
    else:
        w(f"- **{SEC_NAME[sec]}**: 전·후반 둘 다 채점된 애널리스트가 5명 미만이라 지속성을 잴 수 없다 — 원장 이력이 2024–2026 에 몰려 있다.")
w("")
w("정확도가 분기마다 바뀌면 '지난번에 잘 맞힌 사람'을 무겁게 쓰는 것은 노이즈를 키운다. 이 결과는 이 원장의 이력 길이(대부분 2024–2026, 업종당 순위권 10–18명)에서의 판정이다. "
  "분기 실적이 나올 때마다 다시 돌려 지속성이 생기는지 본다 — 생기면 가중을 기본값으로 올린다.")
w("")

w(f"## 4. {P['target']} 영업이익 — 기본(중앙값) · 상위3 가중 · 네이버 컨센")
w("")
for sec, d in R["sectors"].items():
    rows = [(t, s) for t, s in d["stocks"].items() if s.get("n", 0) >= 3]
    if not rows:
        continue
    top = set(d["top"])
    w(f"### {SEC_NAME[sec]} (상위 3명: {', '.join(d['top'])})")
    w("")
    w("| 종목 | 추정 수 | **중앙값(기본)** | 단순 평균 | 상위3 ×2 가중 | 네이버 컨센 | 중앙값 vs 컨센 | 상위 3명 추정 |")
    w("|---|---:|---:|---:|---:|---:|---:|---|")
    for t, s in sorted(rows, key=lambda kv: -kv[1]["n"]):
        nc = s.get("naver_cons")
        gap = f"{(s['median'] / nc - 1) * 100:+.1f}%".replace("-", "−") if nc else "—"
        tops = " · ".join(f"{e['analyst']}({e['firm']}) {f0(e['val'])}" for e in s["estimates"] if e.get("analyst") in top) or "—"
        w(f"| {s['name']} | {s['n']} | **{f0(s['median'])}** | {f0(s['eq_mean'])} | {f0(s['w_mean'])} | {f0(nc)} | {gap} | {tops} |")
    w("")
w("> 단위 억원. 추정 3명 이상 종목만. '중앙값 vs 컨센' 이 음수면 최근 리포트들이 네이버 컨센보다 낮게 본다는 뜻 — 컨센이 아직 덜 내려왔을 수 있다.")
w("")

w("## 5. 한계와 다음 단계")
w("")
w("- **이력이 짧다.** 원장 리포트·추정표가 2025년 이후에 몰려 있어(예: 조선 30종목 리포트 2023년 86건 → 2026년 333건) 업종당 순위권이 10–18명이고 대부분 3–16개 분기다. 2021–2023 리포트 PDF 를 백필하고 추정표를 재파싱하면 표본이 커진다.")
w("- **이름.** 원장 `analyst` 칸에 본문 낱말이 섞여 있어(‘기대’·‘전망이’·‘추정한다’) 이메일을 신원으로 묶고, 한글 3자·어미 제외 규칙을 썼다. 2자·4자 실명(예: 외자 이름)은 빠질 수 있다. 같은 이메일의 이름 변형('석오'/'강석오')은 하나로 합쳤다.")
w("- **단위.** 리포트마다 억/십억 라벨이 틀린 행이 있어, 같은 리포트의 과거 분기 실적을 DART 와 맞춰 리포트별로 보정했다. 보정 뒤에도 10^1.5 배 넘게 어긋난 행은 버렸다(업종별 4–119행).")
w("- **채점은 영업이익 하나.** 매출·순이익·목표가 정확도는 아직 안 본다. 목표가는 '맞았다'의 기준(12개월 뒤 주가)이 이 원장 기간으로는 거의 성숙하지 않았다.")
w("- **실행.** `python3 _scripts/애널리스트_정확도_가중컨센.py --universe … --out … [--top 3 --w-top 2 --w-rest 1 --target 4Q26 --asof …]` → 이 문서 스크립트. 분기 실적 시즌이 끝날 때마다 재실행한다.")
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(L) + "\n")
print("wrote", sys.argv[2])
