def qlabel(d):
    y, m = d[2:4], int(d[5:7])
    return f"{(m - 1) // 3 + 1}Q{y}"


def won(x):
    return f"{int(round(x)):,}"


def pct(x, nd=1):
    q = Decimal(str(x)).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP)
    return (f"+{q}" if q > 0 else str(q)).replace("-", "−") + "%"


def p1(x):
    return f"{Decimal(str(x)).quantize(Decimal('0.1'), rounding=ROUND_HALF_UP)}%"


def dq(code, d, item):
    return HIST.get(code, {}).get("dart_q", {}).get(f"{d}|{item}")


def cons(code, key, which="last"):
    c = HIST.get(code, {}).get("naver_cons", {}).get(key)
    return c[which][1] if c else None


def q3_yoy(code):
    c, base = cons(code, "2026Q3E|op_income"), dq(code, "2025-09-30", "op_income")
    if c is None or not base:
        return None
    return (c / base - 1) * 100


def opm(code, ds):
    op = [dq(code, d, "op_income") for d in ds]
    rv = [dq(code, d, "revenue") for d in ds]
    if None in op or None in rv:
        return None
    return sum(op) / sum(rv) * 100


